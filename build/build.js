#!/usr/bin/env node
/**
 * Assembles the component-based source tree into a plain static site in dist/.
 *
 * Source layout (edit these):
 *   build/template.html        page skeleton with <!--@include:name--> markers
 *   components/<name>/         one folder per site section (home, about, resume,
 *                               travel, dining, gallery, contact) — each may
 *                               contain <name>.html, <name>.css, <name>.js,
 *                               img/, data/, scripts/
 *   theme/                     third-party N5 template + UI plugins (unmodified)
 *   assets/                    Morris's own shared css/js/img used site-wide
 *   bootstrap/, vendor/        third-party libraries (vendor/ is generated by
 *                              `npm install` via scripts/vendor-assets.js)
 *
 * Output (never edit by hand — regenerated every build):
 *   dist/                      flat static site, ready for GitHub Pages
 *
 * Run: node build/build.js   (or `npm run build`)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dist = path.join(root, 'dist');

const COMPONENTS = [
  'home', 'about', 'resume', 'travel', 'dining', 'faith', 'gallery', 'contact',
];

function rmrf(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
}

function copyFile(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function copyDir(src, dest) {
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(from, to);
    else copyFile(from, to);
  }
}

function copyFlat(src, destDir) {
  // Copy every file directly inside src (non-recursive) into destDir.
  if (!fs.existsSync(src)) return;
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (entry.isFile()) copyFile(path.join(src, entry.name), path.join(destDir, entry.name));
  }
}

function assembleIndex() {
  const templatePath = path.join(root, 'build', 'template.html');
  let html = fs.readFileSync(templatePath, 'utf8');
  html = html.replace(/[ \t]*<!--@include:([a-z-]+)-->/g, (match, name) => {
    const partial = path.join(root, 'components', name, `${name}.html`);
    if (!fs.existsSync(partial)) {
      throw new Error(`build.js: no partial found for <!--@include:${name}--> at ${partial}`);
    }
    return fs.readFileSync(partial, 'utf8').replace(/\s+$/, '');
  });
  fs.mkdirSync(dist, { recursive: true });
  fs.writeFileSync(path.join(dist, 'index.html'), html);
}

function main() {
  rmrf(dist);
  fs.mkdirSync(dist, { recursive: true });

  // Third-party libraries (unmodified) — copied verbatim.
  copyDir(path.join(root, 'bootstrap'), path.join(dist, 'bootstrap'));
  if (fs.existsSync(path.join(root, 'vendor'))) {
    copyDir(path.join(root, 'vendor'), path.join(dist, 'vendor'));
  } else {
    console.warn('build.js: vendor/ not found — run `npm install` first (it vendors Font Awesome + Google Fonts).');
  }

  // N5 template + its bundled plugins (css/js/fonts), unmodified.
  copyFlat(path.join(root, 'theme', 'css'), path.join(dist, 'css'));
  copyFlat(path.join(root, 'theme', 'js'), path.join(dist, 'js'));
  copyFlat(path.join(root, 'theme', 'fonts'), path.join(dist, 'fonts'));

  // Morris's own shared/global styles, scripts, and images.
  copyFlat(path.join(root, 'assets', 'css'), path.join(dist, 'css'));
  copyFlat(path.join(root, 'assets', 'js'), path.join(dist, 'js'));
  copyFlat(path.join(root, 'assets', 'img'), path.join(dist, 'img'));

  // Each component contributes its own css/js/img/data into the flat output
  // folders that today's paths (css/, js/, img/<component>/, data/) expect.
  for (const name of COMPONENTS) {
    const compDir = path.join(root, 'components', name);
    if (!fs.existsSync(compDir)) continue;
    for (const entry of fs.readdirSync(compDir, { withFileTypes: true })) {
      if (entry.isFile() && entry.name.endsWith('.css')) {
        copyFile(path.join(compDir, entry.name), path.join(dist, 'css', entry.name));
      } else if (entry.isFile() && entry.name.endsWith('.js')) {
        copyFile(path.join(compDir, entry.name), path.join(dist, 'js', entry.name));
      }
    }
    copyDir(path.join(compDir, 'img'), path.join(dist, 'img', name));
    copyFlat(path.join(compDir, 'data'), path.join(dist, 'data'));
  }

  assembleIndex();
  fs.writeFileSync(path.join(dist, '.nojekyll'), '');

  console.log(`Built site into ${path.relative(root, dist)}/`);
}

main();

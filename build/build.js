const FA_WEBFONTS = [
  'fa-solid-900.woff2',
  'fa-brands-400.woff2',
];

function rmrf(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
}

function copyFile(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function copyDir(src, dest) {
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(from, to);
    else copyFile(from, to);
  }
}

function copyListed(srcDir, destDir, names) {
  for (const name of names) {
    const from = path.join(srcDir, name);
    if (!fs.existsSync(from)) {
      console.warn(`build.js: missing ${path.relative(root, from)}`);
      continue;
    }
    copyFile(from, path.join(destDir, name));
  }
}

function assembleIndex() {
  const templatePath = path.join(root, 'build', 'template.html');
  let html = fs.readFileSync(templatePath, 'utf8');
  html = html.replace(/[ \t]*<!--@include:([a-z-]+)-->/g, (match, name) => {
    const partial = path.join(root, 'components', name, `${name}.html`);
    if (!fs.existsSync(partial)) {
      throw new Error(`build.js: no partial found for <!--@include:${name}--> at ${partial}`);
    }
    return fs.readFileSync(partial, 'utf8').replace(/\s+$/, '');
  });
  fs.mkdirSync(dist, { recursive: true });
  fs.writeFileSync(path.join(dist, 'index.html'), html);
}

function writeRoutePages() {
  const html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
  for (const route of ROUTES) {
    const dir = path.join(dist, route);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'index.html'), html);
  }
  fs.writeFileSync(path.join(dist, '404.html'), html);
}

function copyVendor() {
  const vendor = path.join(root, 'vendor');
  if (!fs.existsSync(vendor)) {
    console.warn('build.js: vendor/ not found — run `npm install` first (it vendors Font Awesome + fonts + leaflet + marked).');
    return;
  }

  copyFile(
    path.join(vendor, 'fontawesome', 'css', 'all.min.css'),
    path.join(dist, 'vendor', 'fontawesome', 'css', 'all.min.css')
  );
  copyListed(
    path.join(vendor, 'fontawesome', 'webfonts'),
    path.join(dist, 'vendor', 'fontawesome', 'webfonts'),
    FA_WEBFONTS
  );
  copyListed(path.join(vendor, 'fonts'), path.join(dist, 'vendor', 'fonts'), VENDOR_FONTS);
  fs.writeFileSync(path.join(dist, 'vendor', 'fonts', 'fonts.css'), FONT_FACE_CSS);

  const leaflet = path.join(vendor, 'leaflet');
  if (fs.existsSync(leaflet)) {
    copyDir(leaflet, path.join(dist, 'vendor', 'leaflet'));
  }
  const marked = path.join(vendor, 'marked');
  if (fs.existsSync(marked)) {
    copyDir(marked, path.join(dist, 'vendor', 'marked'));
  }
}

function main() {
  rmrf(dist);
  fs.mkdirSync(dist, { recursive: true });

  copyFile(
    path.join(root, 'bootstrap', 'css', 'bootstrap.min.css'),
    path.join(dist, 'bootstrap', 'css', 'bootstrap.min.css')
  );

  copyVendor();

  copyListed(path.join(root, 'theme', 'css'), path.join(dist, 'css'), THEME_CSS);
  copyListed(path.join(root, 'theme', 'js'), path.join(dist, 'js'), THEME_JS);

  copyDir(path.join(root, 'assets', 'css'), path.join(dist, 'css'));
  copyDir(path.join(root, 'assets', 'js'), path.join(dist, 'js'));
  copyDir(path.join(root, 'assets', 'img'), path.join(dist, 'img'));

  for (const name of COMPONENTS) {
    const compDir = path.join(root, 'components', name);
    if (!fs.existsSync(compDir)) continue;
    for (const entry of fs.readdirSync(compDir, { withFileTypes: true })) {
      if (entry.isFile() && entry.name.endsWith('.css')) {
        copyFile(path.join(compDir, entry.name), path.join(dist, 'css', entry.name));
      } else if (entry.isFile() && entry.name.endsWith('.js')) {
        copyFile(path.join(compDir, entry.name), path.join(dist, 'js', entry.name));
      }
    }
    if (!SKIP_IMG.has(name)) {
      copyDir(path.join(compDir, 'img'), path.join(dist, 'img', name));
    }
    copyDir(path.join(compDir, 'data'), path.join(dist, 'data'));
  }

  assembleIndex();
  writeRoutePages();
  fs.writeFileSync(path.join(dist, '.nojekyll'), '');

  console.log(`Built site into ${path.relative(root, dist)}/`);
}

main();
